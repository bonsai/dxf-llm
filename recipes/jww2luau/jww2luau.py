#!/usr/bin/env python
"""jww2luau — JWW/DXF の 2D 図面から Roblox (Luau) の 3D 生成コードを作る

使い方:
    python jww2luau.py plan.dxf -o out/Building.luau [--emit-json]

DXF の LINE / LWPOLYLINE を読み、レイヤ名で部材種別を判定して
Roblox の Part を組み立てる Luau ModuleScript を出力する。

ライセンス: MIT / PyDXF Japan
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional

try:
    import ezdxf
except ImportError:  # pragma: no cover
    print("ezdxf が必要です: pip install ezdxf", file=sys.stderr)
    raise

# --- デフォルトのレイヤ → 部材マッピング ------------------------------------

# 語（部分一致）: {kind, height_mm, thickness_mm, color}
DEFAULT_MAPPING: Dict[str, Dict[str, Any]] = {
    "wall":   {"kind": "wall",   "height": 2400, "thickness": 120, "color": "LightStoneGrey"},
    "壁":     {"kind": "wall",   "height": 2400, "thickness": 120, "color": "LightStoneGrey"},
    "column": {"kind": "column", "height": 2800, "thickness": 300, "color": "DarkStoneGrey"},
    "柱":     {"kind": "column", "height": 2800, "thickness": 300, "color": "DarkStoneGrey"},
    "window": {"kind": "window", "height": 1200, "thickness": 100, "color": "Cyan"},
    "窓":     {"kind": "window", "height": 1200, "thickness": 100, "color": "Cyan"},
    "door":   {"kind": "door",   "height": 2000, "thickness": 80,  "color": "Brown"},
    "扉":     {"kind": "door",   "height": 2000, "thickness": 80,  "color": "Brown"},
    "ドア":   {"kind": "door",   "height": 2000, "thickness": 80,  "color": "Brown"},
    "beam":   {"kind": "beam",   "height": 400,  "thickness": 200, "color": "ReddishBrown"},
    "梁":     {"kind": "beam",   "height": 400,  "thickness": 200, "color": "ReddishBrown"},
}

FALLBACK = {"kind": "marker", "height": 100, "thickness": 100, "color": "Yellow"}


@dataclass
class Segment:
    """3D 化の最小単位（線分）。"""
    x1: float
    y1: float
    x2: float
    y2: float
    kind: str
    layer: str
    height: float
    thickness: float
    color: str
    metadata: Dict[str, Any] = field(default_factory=dict)

    @property
    def length(self) -> float:
        return math.hypot(self.x2 - self.x1, self.y2 - self.y1)

    @property
    def angle_deg(self) -> float:
        return math.degrees(math.atan2(self.y2 - self.y1, self.x2 - self.x1))

    @property
    def mid(self) -> tuple[float, float]:
        return ((self.x1 + self.x2) / 2.0, (self.y1 + self.y2) / 2.0)


def classify_layer(layer: str, mapping: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    """レイヤ名から部材種別を推定（部分一致、大文字小文字無視）。"""
    low = layer.lower()
    for key, spec in mapping.items():
        if key.lower() in low:
            return spec
    return FALLBACK


def extract_segments(
    dxf_path: str,
    mapping: Dict[str, Dict[str, Any]],
    min_length_mm: float = 10.0,
) -> List[Segment]:
    """DXF から線分セグメントを抽出。"""
    doc = ezdxf.readfile(dxf_path)
    msp = doc.modelspace()
    segments: List[Segment] = []

    for e in msp:
        etype = e.dxftype()
        layer = e.dxf.layer or "0"
        spec = classify_layer(layer, mapping)

        points: List[tuple[float, float]] = []

        if etype == "LINE":
            s, t = e.dxf.start, e.dxf.end
            points = [(s.x, s.y), (t.x, t.y)]

        elif etype in ("LWPOLYLINE", "POLYLINE"):
            try:
                pts = list(e.get_points("xy")) if etype == "LWPOLYLINE" else [(v.dxf.location.x, v.dxf.location.y) for v in e.vertices]
            except Exception:
                pts = []
            points = [(float(p[0]), float(p[1])) for p in pts]

        else:
            continue

        for i in range(len(points) - 1):
            (x1, y1), (x2, y2) = points[i], points[i + 1]
            seg = Segment(
                x1=x1, y1=y1, x2=x2, y2=y2,
                kind=spec["kind"], layer=layer,
                height=spec["height"], thickness=spec["thickness"],
                color=spec["color"],
            )
            if seg.length >= min_length_mm:
                segments.append(seg)

    return segments


# --- Luau コード生成 ---------------------------------------------------------

LUAU_HEADER = """--!strict
-- Auto-generated by jww2luau (PyDXF Japan)
-- Source DXF: {source}
-- Segments: {count}
-- Scale: 1 meter = {spm} studs

local PART_DATA: {{ [number]: {{ [string]: any }} }} = {data}

local M = {{}}

local function makePart(spec: {{ [string]: any }}): Part
\tlocal p = Instance.new("Part")
\tp.Name = spec.kind .. "_" .. tostring(spec.index)
\tp.Anchored = true
\tp.CanCollide = true
\tp.Size = Vector3.new(spec.size.x, spec.size.y, spec.size.z)
\tp.CFrame = CFrame.new(spec.pos.x, spec.pos.y, spec.pos.z)
\t\t* CFrame.Angles(0, math.rad(spec.rotY), 0)
\ttp.Color = spec.color
\tp.Material = Enum.Material.Concrete
\treturn p
end

-- build(parent, filter?)
-- filter: {{ wall = true, column = true, ... }} を指定すると該当種別のみ生成
function M.build(parent: Instance?, filter: {{ [string]: boolean }}?): Folder
\tlocal root = Instance.new("Folder")
\troot.Name = "JWW_Building"
\tparent = parent or workspace

\tfor _, spec in ipairs(PART_DATA) do
\t\tif filter == nil or filter[spec.kind] then
\t\t\tmakePart(spec):Clone().Parent = root
\t\tend
\tend

\trender(root, parent)
\treturn root
end

function render(model: Folder, parent: Instance)
\tmodel.Parent = parent
end

return M
"""


def color_to_rgb(name: str) -> tuple[int, int, int]:
    """Roblox の BrickColor 名 → 近似 RGB（0-255）。"""
    table = {
        "LightStoneGrey": (163, 162, 165),
        "DarkStoneGrey": (99, 95, 98),
        "Cyan": (4, 175, 236),
        "Brown": (124, 92, 70),
        "ReddishBrown": (112, 67, 42),
        "Yellow": (245, 205, 48),
    }
    return table.get(name, (163, 162, 165))


def build_part_data(segments: List[Segment], studs_per_meter: float, base_height_mm: float) -> List[Dict[str, Any]]:
    """Segment 群を Roblox Part のスペックに変換。"""
    mm = 1.0 / 280.0 if studs_per_meter <= 0 else (1.0 / (1000.0 / studs_per_meter))
    parts = []
    for i, s in enumerate(segments):
        mx, my = s.mid
        r, g, b = color_to_rgb(s.color)
        parts.append({
            "index": i,
            "kind": s.kind,
            "layer": s.layer,
            "size": {
                "x": round(s.length * mm, 4),     # 長さ → X
                "y": round(s.height * mm, 4),     # 高さ → Y
                "z": round(s.thickness * mm, 4),  # 厚み → Z
            },
            "pos": {
                "x": round(mx * mm, 4),
                "y": round((base_height_mm + s.height / 2.0) * mm, 4),
                "z": round(my * mm, 4),
            },
            "rotY": round(s.angle_deg, 4),
            "color": {"r": r / 255.0, "g": g / 255.0, "b": b / 255.0},
        })
    return parts


def to_luau_table(parts: List[Dict[str, Any]]) -> str:
    """parts を Luau のテーブルリテラル文字列に変換。"""
    lines = ["{"]
    for p in parts:
        lines.append(
            "\t{ index = %d, kind = %r, layer = %r, "
            "size = { x = %s, y = %s, z = %s }, "
            "pos = { x = %s, y = %s, z = %s }, "
            "rotY = %s, color = Color3.new(%s, %s, %s) },"
            % (
                p["index"], p["kind"], p["layer"],
                p["size"]["x"], p["size"]["y"], p["size"]["z"],
                p["pos"]["x"], p["pos"]["y"], p["pos"]["z"],
                p["rotY"],
                round(p["color"]["r"], 4), round(p["color"]["g"], 4), round(p["color"]["b"], 4),
            )
        )
    lines.append("}")
    return "\n".join(lines)


def generate_luau(segments: List[Segment], source: str, studs_per_meter: float, base_height_mm: float) -> str:
    parts = build_part_data(segments, studs_per_meter, base_height_mm)
    data = to_luau_table(parts)
    return LUAU_HEADER.format(
        source=source,
        count=len(segments),
        spm=studs_per_meter,
        data=data,
    )


# --- CLI ---------------------------------------------------------------------

def load_mapping(path: Optional[str]) -> Dict[str, Dict[str, Any]]:
    if not path:
        return DEFAULT_MAPPING
    try:
        import yaml
    except ImportError:
        print("mapping を指定するには PyYAML が必要です", file=sys.stderr)
        raise
    with open(path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    return {**DEFAULT_MAPPING, **data.get("layers", data)}


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="JWW/DXF → Roblox Luau converter")
    ap.add_argument("input", help="入力 DXF ファイル")
    ap.add_argument("-o", "--output", default="out/Building.luau", help="出力 .luau パス")
    ap.add_argument("--emit-json", action="store_true", help="中間 JSON も出力")
    ap.add_argument("--studs-per-meter", type=float, default=3.571, help="スケール（1mあたりstuds）")
    ap.add_argument("--base-height-mm", type=float, default=0.0, help="基準高さ(mm)")
    ap.add_argument("--min-length-mm", type=float, default=10.0, help="無視する最小線長(mm)")
    ap.add_argument("--mapping", help="レイヤマッピング YAML")
    args = ap.parse_args(argv)

    mapping = load_mapping(args.mapping)
    segments = extract_segments(args.input, mapping, min_length_mm=args.min_length_mm)

    if not segments:
        print("警告: 線分が抽出できませんでした（レイヤ/単位を確認してください）", file=sys.stderr)

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)

    luau = generate_luau(segments, source=args.input, studs_per_meter=args.studs_per_meter, base_height_mm=args.base_height_mm)
    out.write_text(luau, encoding="utf-8")
    print(f"Luau 出力: {out} ({len(segments)} segments)")

    if args.emit_json:
        jpath = out.with_suffix(".json")
        jpath.write_text(json.dumps(build_part_data(segments, args.studs_per_meter, args.base_height_mm), ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"JSON 出力: {jpath}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())